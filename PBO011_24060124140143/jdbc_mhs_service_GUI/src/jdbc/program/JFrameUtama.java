    //Menambahkan data mahasiswa ke database
    private void jButtonTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTambahActionPerformed
        // TODO add your handling code here:
        String nama = jTextFieldNama.getText();
        if (!nama.isEmpty()) {
            Mahasiswa mhs = new Mahasiswa();
            mhs.setNama(nama);
            service.add(mhs);
            tampilkanSemuaData();
            jTextFieldNama.setText("");
        }
    }//GEN-LAST:event_jButtonTambahActionPerformed

    //Menampilkan seluruh data mahasiswa dari database
    private void jButtonAmbilAllDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAmbilAllDataActionPerformed
        // TODO add your handling code here:
        tampilkanSemuaData();
    }//GEN-LAST:event_jButtonAmbilAllDataActionPerformed

    //Mengubah data mahasiswa berdasarkan id
    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        // TODO add your handling code here:
        try {
            int id = Integer.parseInt(jTextFieldIDEdit.getText());
            String nama = jTextFieldNamaEdit.getText();
            Mahasiswa mhs = new Mahasiswa(id, nama);
            service.update(mhs);
            tampilkanSemuaData();
            jTextFieldIDEdit.setText("");
            jTextFieldNamaEdit.setText("");
        } catch (NumberFormatException e) {
            System.out.println("ID harus angka!");
        }
    }//GEN-LAST:event_jButtonEditActionPerformed

    //Menghapus data mahasiswa berdasarkan id
    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
        // TODO add your handling code here:
        try {
            int id = Integer.parseInt(jTextFieldIDHapus.getText());
            service.delete(id);
            tampilkanSemuaData();
            jTextFieldIDHapus.setText("");
            jTextFieldNamaHapus.setText("");
        } catch (NumberFormatException e) {
            System.out.println("ID harus angka!");
        }
    }//GEN-LAST:event_jButtonHapusActionPerformed

