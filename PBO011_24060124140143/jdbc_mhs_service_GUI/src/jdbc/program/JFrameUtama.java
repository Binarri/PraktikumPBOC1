    //Menampilkan seluruh data mahasiswa ke komponen JList
    private void tampilkanSemuaData() {
        dlmID.clear();
        dlmNama.clear();
        List<Mahasiswa> list = service.getAll();
        for (Mahasiswa m : list) {
            dlmID.addElement(String.valueOf(m.getId()));
            dlmNama.addElement(m.getNama());
        }
    }

